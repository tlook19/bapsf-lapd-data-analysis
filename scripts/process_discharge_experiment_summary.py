"""Compute robust discharge summaries for experiment-set labeling."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.ndimage import uniform_filter1d

from bapsf_lapd import LapdDataset


MANIFEST = Path("config/may2026_run_manifest.toml")
OUTPUT = Path("processed/discharge_experiment_set_summary.toml")
SMOOTHING_SAMPLES = 9


@dataclass(frozen=True)
class RunDischargeSummary:
    run_id: str
    experiment_set_id: int
    trace_index: int
    sample_index: int
    time_s: float
    peak_current_a: float
    discharge_voltage_v: float
    peak_power_w: float


def robust_run_summary(run) -> RunDischargeSummary:
    """Use smoothed peak power to avoid current spikes at discharge shutoff.

    The run's additive discharge-current zero offset
    (``LapdRun.discharge_zero_offset_stats``) is subtracted before smoothing,
    so the reported current and power are offset-corrected.
    """
    current, voltage, time_s = run.discharge_traces()
    current = current - run.discharge_zero_offset_stats().offset_a

    current_smooth = uniform_filter1d(
        current,
        size=SMOOTHING_SAMPLES,
        axis=1,
        mode="nearest",
    )
    voltage_smooth = uniform_filter1d(
        np.abs(voltage),
        size=SMOOTHING_SAMPLES,
        axis=1,
        mode="nearest",
    )
    power_smooth = current_smooth * voltage_smooth

    valid = (
        (time_s >= 0)
        & (time_s <= 0.021)
        & (current_smooth > 0)
        & (voltage_smooth > 20)
    )
    masked_power = np.where(valid, power_smooth, np.nan)
    trace_index, sample_index = np.unravel_index(
        int(np.nanargmax(masked_power)),
        masked_power.shape,
    )

    return RunDischargeSummary(
        run_id=run.config.run_id,
        experiment_set_id=run.config.experiment_set.id,
        trace_index=int(trace_index),
        sample_index=int(sample_index),
        time_s=float(time_s[sample_index]),
        peak_current_a=float(current_smooth[trace_index, sample_index]),
        discharge_voltage_v=float(voltage_smooth[trace_index, sample_index]),
        peak_power_w=float(power_smooth[trace_index, sample_index]),
    )


def _mean(values: list[float]) -> float:
    return float(np.mean(values))


def _std(values: list[float]) -> float:
    return float(np.std(values, ddof=1)) if len(values) > 1 else 0.0


def _toml_float(value: float) -> str:
    return f"{value:.9g}"


def main() -> None:
    dataset = LapdDataset.from_manifest(MANIFEST)
    run_summaries = [robust_run_summary(dataset.run(run_id)) for run_id in dataset.run_ids()]

    lines = [
        "# Generated by scripts/process_discharge_experiment_summary.py",
        "[method]",
        'description = "Robust discharge metrics use a 9-sample moving average and choose the peak of I * abs(V) within 0-21 ms, excluding low-voltage shutoff current spikes. Each run\'s additive discharge-current zero offset is subtracted before smoothing."',
        f"smoothing_samples = {SMOOTHING_SAMPLES}",
        'peak_selection = "max(smoothed_current_a * smoothed_abs_voltage_v)"',
        "valid_time_min_s = 0.0",
        "valid_time_max_s = 0.021",
        "valid_abs_voltage_min_v = 20.0",
        "",
    ]

    for experiment_set_id in dataset.experiment_set_ids():
        summaries = [item for item in run_summaries if item.experiment_set_id == experiment_set_id]
        currents = [item.peak_current_a for item in summaries]
        voltages = [item.discharge_voltage_v for item in summaries]
        powers = [item.peak_power_w for item in summaries]
        experiment = dataset.config(summaries[0].run_id).experiment_set

        lines.extend(
            [
                f'[experiment_sets."{experiment_set_id}"]',
                f'label = "{experiment.label}"',
                f"v_bank = {_toml_float(experiment.v_bank)}",
                f"v_puff = {_toml_float(experiment.v_puff)}",
                f"n_runs = {len(summaries)}",
                f"peak_current_mean_a = {_toml_float(_mean(currents))}",
                f"peak_current_std_a = {_toml_float(_std(currents))}",
                f"discharge_voltage_mean_v = {_toml_float(_mean(voltages))}",
                f"discharge_voltage_std_v = {_toml_float(_std(voltages))}",
                f"peak_power_mean_w = {_toml_float(_mean(powers))}",
                f"peak_power_std_w = {_toml_float(_std(powers))}",
                f"peak_power_mean_kw = {_toml_float(_mean(powers) / 1e3)}",
                f"peak_power_std_kw = {_toml_float(_std(powers) / 1e3)}",
                "",
            ]
        )

    for summary in run_summaries:
        lines.extend(
            [
                f'[runs."{summary.run_id}"]',
                f"experiment_set = {summary.experiment_set_id}",
                f"trace_index = {summary.trace_index}",
                f"sample_index = {summary.sample_index}",
                f"time_s = {_toml_float(summary.time_s)}",
                f"peak_current_a = {_toml_float(summary.peak_current_a)}",
                f"discharge_voltage_v = {_toml_float(summary.discharge_voltage_v)}",
                f"peak_power_w = {_toml_float(summary.peak_power_w)}",
                f"peak_power_kw = {_toml_float(summary.peak_power_w / 1e3)}",
                "",
            ]
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
